#include "config.h"
#define __ASSEMBLY__


    .section .entry, "ax"
    .globl   _entry
    .extern  _start
_entry:
	e_b _start

/*
 *  _start
 *
 *  PowerPC EABI Runtime Initialization.  Initialize pointers,
 *  initialize data, and call main().
 *
 *  This function is the very first location executed in a program, or
 *  the first location called by the board-level initialization.
 *  Memory access is not guaranteed to be safe until after __init_hardware.
 */

    .section .startup, "ax"
    .globl _start

_start:
    se_mtar     r14, r3
    se_mtar     r15, r4
    se_mtar     r16, r5

    /*
     *  PowerPC init registers
     */
    e_bl        __init_registers

    /*
     *  board-level initialization, memory access is ok following __init_hardware call
     */
     e_bl       __init_hardware

    /*
     *  prepare a terminating stack record.
     */
    e_stwu      r1, -16(r1)       /* SP is required to always be 16-byte aligned */
    se_li       r0, 0
    se_stw      r0, 0(r1)         /* EABI requires that initial back chain word should be null */
    se_bmaski   r0, 0             /* load up r0 with 0xFFFFFFFF */
    se_stw      r0, 4(r1)         /* Make an illegal return address of 0xFFFFFFFF */

    /*
    *  data initialization
    */
    /* e_bl        __init_data */

    /*
     *  user initialization before main
     */
    e_lis       r3, __init_user@ha
    e_add16i    r3, r3, __init_user@l
    se_mtlr     r3
    se_blrl

    /* DMEM initialization */
    e_bl __Init_Dmem

    /*
    *  branch to main program
    */
    e_lis       r6, main@ha
    e_add16i    r6, r6, main@l
    se_mtlr     r6
    se_mfar     r3, r14
    se_mfar     r4, r15
    se_mfar     r5, r16
    se_blrl

/*
 *  __init_registers
 *
 *  Initialize PowerPC Registers
 *
 *  Note: this function is guaranteed to not reference any memory; the memory
 *  controller may not be initialized.
 *
 *  User may re-define __init_registers
 *
 */

__init_registers:

    /*
     *  initialize stack pointer
     */
    e_lis       r1, _stack_addr@h     /* _stack_addr is generated by linker */
    e_or2i      r1, _stack_addr@l

    /*
     *  initialize small data area pointers (EABI)
     */
    e_lis       r2, _SDA2_BASE_@h     /* _SDA2_BASE_ is generated by linker */
    e_or2i      r2, _SDA2_BASE_@l

    e_lis       r13, _SDA_BASE_@h     /* _SDA_BASE_ is generated by linker */
    e_or2i      r13, _SDA_BASE_@l

    /*
     * Clear nested interrupt count
     */
    e_lis r4, 0
    mtsprg    0, r4
    /*
     *  set MSR
     */
    mfmsr       r6
    e_ori       r6, r6, 0x0200        /* Debug Interrupt Enable, DE */
    mtmsr       r6
    se_isync


    /*
     * init interrupt vectors
     */

    e_lis       r3, gInterruptVectorTable@h
    e_or2i      r3, gInterruptVectorTable@l

    /* e_rlwinm    r0, r3, 0, 0, 15 */
    e_rlwinm    r0, r3, 0, 0, 24 // remove low 8 bits, => table it should be 256 bits align!
    mtspr       63, r0              /* IVPR */

    se_blr

/*
 * __init_hardware
 *
 * Board level initializations
 *
 * User may re-define this function
 */

__init_hardware:
    se_blr

/*
 *  __init_data
 *
 *  Initialize all RAM data sections
 *
 *  dst     destination RAM address
 *  size    number of bytes to zero
 *
 *  User may re-define __init_data
 *
 */
__init_data:
/******************************* Initialize BSS section ******************************/
bss_Init:
    e_lis        r9, __bss_size@h       # Load upper BSS load size (# of bytes) into R9
    e_or2i       r9, __bss_size@l       # Load lower BSS load size into R9 and compare to zero
    e_cmp16i     r9,0
    e_beq        bss_Init_end           # Exit if size is zero (no data to initialise)

    mtctr        r9                     # Store no. of bytes to be moved in counter

    e_lis        r5, __bss_start@h      # Load upper BSS address into R5 (from linker file)
    e_or2i       r5, __bss_start@l      # Load lower BSS address into R5 (from linker file)
    e_subi       r5, r5, 1              # Decrement address to prepare for bss_Init_loop

    e_lis        r4, 0x0

bss_Init_loop:
    e_stbu       r4, 1(r5)              # Store zero byte into BSS at R5 and update BSS address
    e_bdnz       bss_Init_loop          # Branch if more bytes to load

bss_Init_end:
    se_blr

/*
 * __init_user
 * User level initializations
 *
 * User may re-define this function
 */

__init_user:
    se_blr

__Init_Dmem:
 e_lis r3, __bss_start@h
 e_or2i r3, __bss_start@l
 se_li   r4,0
 e_lis r5, __bss_size@h
 e_or2i r5, __bss_size@l
 e_b memset

